"""Generate runtime/src/bcpack_tables.inc from the Python BCPack tables.

The native decoder (`runtime/src/bcpack.cpp`) reads the same codec constants as `tools/bcpack.py`: the rANS
probability models, the BC1/BC3/BC4/BC5 symbol and built-in history tables (`bcpack_tables.py`) and the public
BPTC partition, anchor and BC7 signature tables (`bcpack_tables_bptc.py`). This script writes them as C++ so the
two decoders cannot drift apart; `tests/test_bcpack_native.py` fails when the checked-in file is stale.

    python -I tools/gen_bcpack_tables.py            # rewrite runtime/src/bcpack_tables.inc
    python -I tools/gen_bcpack_tables.py --check    # exit 1 if it is out of date
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bcpack as _bcpack  # noqa: E402
import bcpack_tables as _tables  # noqa: E402
import bcpack_tables_bptc as _bptc  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "runtime", "src", "bcpack_tables.inc")


def _rows(values, per_line=16, fmt=str):
    items = [fmt(v) for v in values]
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("    " + ", ".join(items[i:i + per_line]) + ",")
    return "\n".join(lines)


def _history(name, confirmed, provisional, ncols):
    """`<name>_history_state[256]` (0 none, 1 confirmed, 2 provisional) and `<name>_history[256][ncols]`.

    A provisional entry that is also confirmed is dropped, as `bcpack._resolve_bc_history` does."""
    state = [0] * 256
    vals = [(0,) * ncols] * 256
    for k, v in provisional.items():
        if k not in confirmed:
            state[k], vals[k] = 2, tuple(v)
    for k, v in confirmed.items():
        state[k], vals[k] = 1, tuple(v)
    for v in vals:
        assert len(v) == ncols
    body = "\n".join("    {" + ", ".join(str(x) for x in v) + "}," for v in vals)
    return (
        f"inline constexpr std::uint8_t {name}_history_state[256] = {{\n{_rows(state, 32)}\n}};\n"
        f"inline constexpr std::uint8_t {name}_history[256][{ncols}] = {{\n{body}\n}};\n"
    )


def _rank_of():
    cells = sorted(((a, b) for a in range(32) for b in range(16)), key=lambda ab: ((ab[0] + 1) * (ab[1] + 1), ab[0]))
    rank_of = [-1] * 512
    for rank, (a, b) in enumerate(cells):
        if rank < len(_bptc.BC7_CONFIG):
            rank_of[a * 16 + b] = rank
    return rank_of


def generate():
    out = [
        "// Generated by tools/gen_bcpack_tables.py from tools/bcpack_tables.py and tools/bcpack_tables_bptc.py.",
        "// Do not edit by hand: rerun the generator (tests/test_bcpack_native.py checks it is current).",
        "",
    ]

    # rANS models: prob_freq[w - 1][q][band], band 0..w; unused bands are 0.
    out.append("// (symbol_width, q) -> per-band rANS frequencies; band p covers symbols [2^(p-1), 2^p).")
    out.append("inline constexpr std::uint16_t prob_freq[10][16][11] = {")
    for w in range(1, 11):
        out.append("    {")
        for q in range(16):
            freq = _tables.PROB_TABLES[(w, q)]
            assert len(freq) == w + 1 and all(0 <= f <= 0xFFFF for f in freq)
            row = list(freq) + [0] * (11 - len(freq))
            out.append("        {" + ", ".join(str(f) for f in row) + "},")
        out.append("    },")
    out.append("};")
    out.append("")

    for name, table in (("bc1_quadrant", _tables.BC1_QUADRANT), ("bc3_colour_quadrant", _tables.BC3_COLOUR_QUADRANT)):
        assert len(table) == 256
        out.append(f"inline constexpr std::uint8_t {name}[256] = {{\n{_rows(table, 16)}\n}};")
    for name, pairs in (("bc3_alpha_pair", _tables.BC3_ALPHA_PAIR), ("bc4_pair", _tables.BC4_PAIR),
                        ("bc5_pair", _tables.BC5_PAIR)):
        assert len(pairs) == 64 and all(len(p) == 2 for p in pairs)
        body = _rows([f"{{{p[0]}, {p[1]}}}" for p in pairs], 8)
        out.append(f"inline constexpr std::uint8_t {name}[64][2] = {{\n{body}\n}};")
    out.append("")

    out.append(_history("bc1", _tables.BC1_HISTORY_CONFIRMED, _tables.BC1_HISTORY_PROVISIONAL, 6))
    out.append(_history("bc3", _tables.BC3_HISTORY_CONFIRMED, _tables.BC3_HISTORY_PROVISIONAL, 8))
    out.append(_history("bc4", _tables.BC4_HISTORY_CONFIRMED, _tables.BC4_HISTORY_PROVISIONAL, 2))
    out.append(_history("bc5", _tables.BC5_HISTORY_CONFIRMED, _tables.BC5_HISTORY_PROVISIONAL, 4))

    hexfmt = lambda v: f"0x{v:x}"  # noqa: E731
    out.append(f"inline constexpr std::uint16_t bc7_part2_packed[64] = {{\n{_rows(_bptc.BC7_PART2_PACKED, 8, hexfmt)}\n}};")
    out.append(f"inline constexpr std::uint32_t bc7_part3_packed[64] = {{\n{_rows(_bptc.BC7_PART3_PACKED, 6, hexfmt)}\n}};")
    for name, table in (("bc7_anchor2", _bptc.BC7_ANCHOR2), ("bc7_anchor3a", _bptc.BC7_ANCHOR3A),
                        ("bc7_anchor3b", _bptc.BC7_ANCHOR3B)):
        assert len(table) == 64
        out.append(f"inline constexpr std::uint8_t {name}[64] = {{\n{_rows(table, 16)}\n}};")
    out.append("")

    cfg = _bptc.BC7_CONFIG
    out.append("// BC7 lane-15 signature rank -> (mode, partition, rotation, index_selection); mode 255 = no block.")
    out.append(f"inline constexpr int bc7_config_count = {len(cfg)};")
    body = _rows([f"{{{m}, {p}, {r}, {s}}}" for m, p, r, s in cfg], 6)
    out.append(f"inline constexpr std::uint8_t bc7_config[{len(cfg)}][4] = {{\n{body}\n}};")
    inferred = sorted(_bptc.BC7_CONFIG_INFERRED)
    out.append(f"inline constexpr std::uint16_t bc7_inferred[{len(inferred)}] = {{{', '.join(map(str, inferred))}}};")
    out.append("// Lane-15 symbol pair (a, b) -> signature rank (a * 16 + b), -1 outside the table.")
    out.append(f"inline constexpr std::int16_t bc7_rank_of[512] = {{\n{_rows(_rank_of(), 16)}\n}};")
    out.append("")

    # BC6H modes 1..14 (mode = lane-15 symbol + 1; row 0 unused): (code, transformed, base_bits, dr, dg, db,
    # regions, header_bits), and the header bit plan of `bcpack._bc6h_plan`: (channel, endpoint slot, bit, stream
    # position), channel -1 for the partition field.
    info_rows, plan_counts, plan_rows = ["{0, 0, 0, 0, 0, 0, 0, 0}"], [0], ["{}"]
    max_items = 0
    for mode in range(1, 15):
        code = _bcpack._BC6H_CODE[mode]
        trans, base, deltas, regions = _bcpack._BC6H_INFO[code]
        plan, header = _bcpack._bc6h_plan(code)
        max_items = max(max_items, len(plan))
        info_rows.append(f"{{{code}, {trans}, {base}, {deltas[0]}, {deltas[1]}, {deltas[2]}, {regions}, {header}}}")
        plan_counts.append(len(plan))
        plan_rows.append("{" + ", ".join(f"{{{c}, {q}, {b}, {p}}}" for c, q, b, p in plan) + "}")
    out.append(f"inline constexpr std::uint8_t bc6h_mode_info[15][8] = {{\n{_rows(info_rows, 1)}\n}};")
    out.append(f"inline constexpr std::uint8_t bc6h_plan_count[15] = {{{', '.join(map(str, plan_counts))}}};")
    out.append(f"inline constexpr std::int8_t bc6h_plan[15][{max_items}][4] = {{\n{_rows(plan_rows, 1)}\n}};")
    out.append("")
    return "\n".join(out)


def main(argv):
    text = generate()
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8", newline="") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text:
            print(f"{OUT} is out of date: run python -I tools/gen_bcpack_tables.py", file=sys.stderr)
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
